import { readFileSync, writeFileSync } from 'node:fs';
import { parseManifest } from '../src/renderer/src/render/manifest';
import { buildNotices, buildCreditLines } from '../src/renderer/src/render/creditsText';

const manifest = parseManifest(JSON.parse(readFileSync('public/assets/manifest.json', 'utf8')));
const notices = buildNotices(manifest, (p) => readFileSync(`public/assets/${p}`, 'utf8').replace(/\r\n/g, '\n'));
writeFileSync('public/THIRD_PARTY_NOTICES.txt', notices);
const lines = buildCreditLines(manifest);
writeFileSync('src/renderer/src/render/credits.generated.ts',
  `// Generated by scripts/gen-credits.ts from public/assets/manifest.json. Do not edit.\nexport const CREDITS: readonly string[] = ${JSON.stringify(lines, null, 2)};\n`);
console.log(`wrote public/THIRD_PARTY_NOTICES.txt (${notices.length} chars) and credits.generated.ts (${lines.length} lines)`);
