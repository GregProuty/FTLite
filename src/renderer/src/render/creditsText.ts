import type { Manifest, ManifestEntry } from './manifest';
import { LICENSE_URLS, OWNER_AUTHOR } from './licenses';

/** One attribution block per distinct (title, author, source, license, modifications) across files. */
function groups(m: Manifest): { key: string; entries: ManifestEntry[] }[] {
  const by = new Map<string, ManifestEntry[]>();
  for (const e of m) { const k = [e.title, e.author, e.source, e.license, e.modifications].join('\u0000'); by.set(k, [...(by.get(k) ?? []), e]); }
  return [...by].map(([key, entries]) => ({ key, entries })).sort((a, b) => a.key.localeCompare(b.key));
}

export function buildNotices(m: Manifest, readLicenseFile: (path: string) => string): string {
  const out: string[] = ['FTLite third-party notices', 'Generated by scripts/gen-credits.ts from public/assets/manifest.json. Do not edit by hand.', ''];
  const third = m.filter((e) => e.license !== 'original');
  const licences = [...new Set(third.map((e) => e.license))].sort();
  for (const lic of licences) {
    out.push(`== ${lic} (${LICENSE_URLS[lic as keyof typeof LICENSE_URLS]}) ==`, '');
    for (const g of groups(third.filter((e) => e.license === lic))) {
      const e = g.entries[0]!;
      out.push(e.credit ?? `${e.title} by ${e.author}`);
      out.push(`  Title: ${e.title}`, `  Author: ${e.author}`, `  Source: ${e.source}`);
      if (e.archived) out.push(`  Archived: ${e.archived}`);
      out.push(`  Licence: ${lic} ${e.licenseUrl ?? LICENSE_URLS[lic as keyof typeof LICENSE_URLS]}`);
      out.push(`  Modifications: ${e.modifications}${e.editedBy ? ` (edited by ${e.editedBy})` : ''}`);
      if (e.retrieved) out.push(`  Retrieved: ${e.retrieved}`);
      out.push(`  Files: ${g.entries.map((x) => x.file).sort().join(', ')}`, '');
    }
  }
  const licenseFiles = [...new Set(third.map((e) => e.licenseFile).filter((p): p is string => !!p))].sort();
  for (const p of licenseFiles) out.push(`== Licence text: ${p} ==`, '', readLicenseFile(p).trimEnd(), '');
  return out.join('\n');
}

export function buildCreditLines(m: Manifest): string[] {
  const lines = ['FTLite', ''];
  const seen = new Set<string>();
  for (const g of groups(m.filter((e) => e.license !== 'original'))) {
    const e = g.entries[0]!;
    const line = e.credit ?? `${e.title} by ${e.author}, ${e.license}`;
    if (!seen.has(line)) { seen.add(line); lines.push(line); }
  }
  lines.push('', `Original art: ${OWNER_AUTHOR}`);
  return lines;
}
