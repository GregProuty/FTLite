it('supports injected 16-player codec and ledger without raising game cap', () => {
  const codec = createMessageCodec(16), ledger = createLedger([15], 16);
  const e = { ...envelope(1), id: { player: 15, sequence: 1 } };
  expect(codec.decodeMessage(codec.encodeMessage({ kind: 'command', envelope: e }))).toEqual({ kind: 'command', envelope: e });
  expect(ledger.admit(e, 0)).toEqual({ status: 'queued' }); ledger.finish({ id: e.id, tick: 0, status: 'noop' });
  const copy = createLedger([15], 16); copy.restore(ledger.export()); expect(copy.admit(e, 0).status).toBe('duplicate');
  expect(() => encodeMessage({ kind: 'command', envelope: e })).toThrow();
});
